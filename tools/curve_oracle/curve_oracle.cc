/* Quad-precision oracle for the curves library (plan P4a §3.8).
 *
 * Offline tool, never linked into the core and not part of ctest (DEC-002):
 * GCC with libquadmath. It evaluates the fixture definitions in
 * source/ubertopo/tests/support/cesaro_fixtures.h exactly as given (the
 * doubles), by a method independent of the production code: composite
 * Gauss-Legendre directly on e^{i theta(s)}, with nodes computed in quad,
 * at two panel counts that must agree to 1e-28 relative to the curve's
 * length. It writes source/ubertopo/tests/data/curve_oracle.inc.
 *
 * Build and run (WSL, from the repo root):
 *   g++ -O2 -std=gnu++20 -I source tools/curve_oracle/curve_oracle.cc -lquadmath -o /tmp/curve_oracle
 *   /tmp/curve_oracle > source/ubertopo/tests/data/curve_oracle.inc */

#include <quadmath.h>

#include <cstdio>
#include <cstdlib>
#include <vector>

#include "ubertopo/tests/support/cesaro_fixtures.h"

using Q = __float128;
using ubertopo::test::CesaroFixture;

namespace {

constexpr int kNodes = 24;
Q gl_x[kNodes], gl_w[kNodes];

void gl_init()
{
  for (int i = 0; i < kNodes; i++) {
    Q x = cosq(M_PIq * (Q(i) + 0.75Q) / (Q(kNodes) + 0.5Q));
    for (int it = 0; it < 100; it++) {
      Q p0 = 1, p1 = x;
      for (int k = 2; k <= kNodes; k++) {
        const Q p2 = ((2 * k - 1) * x * p1 - (k - 1) * p0) / k;
        p0 = p1;
        p1 = p2;
      }
      const Q dp = kNodes * (x * p1 - p0) / (x * x - 1);
      const Q dx = p1 / dp;
      x -= dx;
      if (fabsq(dx) < 1e-33Q) {
        break;
      }
    }
    Q p0 = 1, p1 = x;
    for (int k = 2; k <= kNodes; k++) {
      const Q p2 = ((2 * k - 1) * x * p1 - (k - 1) * p0) / k;
      p0 = p1;
      p1 = p2;
    }
    const Q dp = kNodes * (x * p1 - p0) / (x * x - 1);
    gl_x[i] = x;
    gl_w[i] = 2 / ((1 - x * x) * dp * dp);
  }
}

struct QSeg {
  Q L, th0, k[4];
  Q theta(Q s) const
  {
    return th0 + s * (k[0] + s * (k[1] / 2 + s * (k[2] / 3 + s * (k[3] / 4))));
  }
  Q kappa_max() const
  {
    Q m = 0;
    for (int i = 0; i <= 64; i++) {
      const Q s = L * i / 64;
      const Q v = fabsq(k[0] + s * (k[1] + s * (k[2] + s * k[3])));
      m = v > m ? v : m;
    }
    return m;
  }
};

/* int_{a}^{b} e^{i theta} over a segment, `panels` per unit of bend scale */
void integrate(const QSeg &g, Q a, Q b, int refine, Q &ix, Q &iy)
{
  ix = iy = 0;
  if (b <= a) {
    return;
  }
  const Q km = g.kappa_max();
  Q h = 2;
  if (km > 0 && 0.02Q / km < h) {
    h = 0.02Q / km;
  }
  long n = long((b - a) / h) + 1;
  n *= refine;
  const Q w = (b - a) / n;
  for (long p = 0; p < n; p++) {
    const Q c = a + w * (p + 0.5Q);
    for (int i = 0; i < kNodes; i++) {
      const Q th = g.theta(c + 0.5Q * w * gl_x[i]);
      ix += gl_w[i] * cosq(th) * 0.5Q * w;
      iy += gl_w[i] * sinq(th) * 0.5Q * w;
    }
  }
}

void eval(const std::vector<QSeg> &segs, Q x0, Q y0, Q s, int refine, Q &x, Q &y, Q &tx, Q &ty)
{
  x = x0;
  y = y0;
  Q acc = 0;
  for (size_t i = 0; i < segs.size(); i++) {
    const QSeg &g = segs[i];
    const bool last = i + 1 == segs.size();
    const Q take = (s - acc < g.L && !last) ? s - acc : (last ? s - acc : g.L);
    Q ix, iy;
    integrate(g, 0, take, refine, ix, iy);
    x += ix;
    y += iy;
    if (s - acc <= g.L || last) {
      const Q th = g.theta(take);
      tx = cosq(th);
      ty = sinq(th);
      return;
    }
    acc += g.L;
  }
}

} // namespace

int main()
{
  gl_init();
  const auto fx = ubertopo::test::cesaro_fixtures();
  printf("/* Generated by tools/curve_oracle from tests/support/cesaro_fixtures.h.\n"
         " * Do not edit: regenerate with the tool when the fixtures change. */\n\n");
  int idx = 0;
  for (const CesaroFixture &f : fx) {
    std::vector<QSeg> segs;
    Q th = f.th0;
    for (auto &s : f.segs) {
      QSeg g;
      g.L = s[0];
      g.th0 = th;
      for (int k = 0; k < 4; k++) {
        g.k[k] = s[k + 1];
      }
      th = g.theta(g.L);
      segs.push_back(g);
    }
    const Q L = ubertopo::test::fixture_length(f);
    printf("static const ubertopo::test::OracleSample kOracle%d[] = {\n", idx);
    for (double s : f.stations) {
      Q x1, y1, tx1, ty1, x2, y2, tx2, ty2;
      eval(segs, f.x0, f.y0, s, 1, x1, y1, tx1, ty1);
      eval(segs, f.x0, f.y0, s, 2, x2, y2, tx2, ty2);
      const Q d = fabsq(x1 - x2) + fabsq(y1 - y2);
      if (d > 1e-28Q * (L + 1)) {
        fprintf(stderr, "%s: panel counts disagree by %g at s = %g\n", f.name, double(d), s);
        return 1;
      }
      printf("  {%a, %a, %a, %a, %a},\n", s, double(x2), double(y2), double(tx2), double(ty2));
    }
    printf("};\n");
    idx++;
  }
  printf("\nstatic const ubertopo::test::OracleSet kCesaroOracle[] = {\n");
  idx = 0;
  for (const CesaroFixture &f : fx) {
    printf("  {\"%s\", kOracle%d, %d},\n", f.name, idx, int(f.stations.size()));
    idx++;
  }
  printf("};\n");
  return 0;
}
