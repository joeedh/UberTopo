/* Quad-precision oracle for road3 (plan P4b §3.2).
 *
 * Offline tool, never linked into the core and not part of ctest (DEC-002):
 * GCC with libquadmath. It evaluates the fixtures of
 * source/ubertopo/tests/support/road_fixtures.h exactly as given (the
 * doubles): the reference by the cesaro quad integration (quad_cesaro.h, two
 * panel counts that must agree), its curvature from the fixture's kappa
 * polynomials, borders and heights by Horner in quad, and S with its
 * partials from the closed forms
 *   S = r + t N + Z e_z,  Z = Z_k + w (Z_(k+1) - Z_k),  w = (t - b_k) / (b_(k+1) - b_k),
 *   N' = -kappa T, N'' = -kappa' T - kappa^2 N, r'' = kappa N.
 * It writes source/ubertopo/tests/data/road_oracle.inc.
 *
 * Build and run (WSL, from the repo root):
 *   g++ -O2 -std=gnu++20 -I source tools/curve_oracle/road_oracle.cc -lquadmath -o /tmp/road_oracle
 *   /tmp/road_oracle > source/ubertopo/tests/data/road_oracle.inc */

#include <quadmath.h>

#include <cstdio>
#include <cstdlib>
#include <vector>

#include "quad_cesaro.h"
#include "ubertopo/tests/support/road_fixtures.h"

using namespace quad_oracle;
using ubertopo::test::FnData;
using ubertopo::test::RoadFixture;

namespace {

/* the k-th derivative of f at s (s strictly inside a piece, or at the domain's ends) */
Q fn_eval(const FnData &f, Q s, int k)
{
  size_t i = 0;
  while (i + 2 < f.breaks.size() && s >= Q(f.breaks[i + 1])) {
    i++;
  }
  const Q sig = s - Q(f.breaks[i]);
  const auto &p = f.pieces[i];
  Q v = 0;
  for (int j = int(p.size()) - 1; j >= k; j--) {
    Q c = p[size_t(j)];
    for (int m = 0; m < k; m++) {
      c *= Q(j - m);
    }
    v = v * sig + c;
  }
  return v;
}

struct Ref {
  std::vector<QSeg> segs;
  Q x0, y0;
  std::vector<std::vector<Q>> kappa; /* per segment, c0..c3 */
  /* kappa and kappa' at s */
  void curvature(Q s, Q &k, Q &k1) const
  {
    Q acc = 0;
    size_t i = 0;
    while (i + 1 < segs.size() && s > acc + segs[i].L) {
      acc += segs[i].L;
      i++;
    }
    const Q sig = s - acc;
    const auto &c = kappa[i];
    k = c[0] + sig * (c[1] + sig * (c[2] + sig * c[3]));
    k1 = c[1] + sig * (2 * c[2] + sig * 3 * c[3]);
  }
};

} // namespace

int main()
{
  gl_init();
  const auto fx = ubertopo::test::road_fixtures();
  printf("/* Generated by tools/curve_oracle/road_oracle from tests/support/road_fixtures.h.\n"
         " * Do not edit: regenerate with the tool when the fixtures change. */\n\n");
  int idx = 0;
  for (const RoadFixture &f : fx) {
    Ref ref;
    ref.x0 = f.ref.x0;
    ref.y0 = f.ref.y0;
    Q th = f.ref.th0, L = 0;
    for (auto &s : f.ref.segs) {
      QSeg g;
      g.L = s[0];
      g.th0 = th;
      for (int k = 0; k < 4; k++) {
        g.k[k] = s[k + 1];
      }
      th = g.theta(g.L);
      ref.segs.push_back(g);
      ref.kappa.push_back({Q(s[1]), Q(s[2]), Q(s[3]), Q(s[4])});
      L += g.L;
    }
    const int m = int(f.borders.size()) - 1;
    printf("static const ubertopo::test::RoadOracleSample kRoad%d[] = {\n", idx);
    for (double sd : f.stations) {
      const Q s = sd;
      Q x1, y1, tx1, ty1, x, y, tx, ty;
      eval(ref.segs, ref.x0, ref.y0, s, 1, x1, y1, tx1, ty1);
      eval(ref.segs, ref.x0, ref.y0, s, 2, x, y, tx, ty);
      if (fabsq(x1 - x) + fabsq(y1 - y) > 1e-28Q * (L + 1)) {
        fprintf(stderr, "%s: panel counts disagree at s = %g\n", f.name, sd);
        return 1;
      }
      Q kap, kap1;
      ref.curvature(s, kap, kap1);
      const Q nx = -ty, ny = tx;
      for (int lk = 0; lk < m; lk++) {
        for (double fr : f.fractions) {
          const Q b0 = fn_eval(f.borders[size_t(lk)], s, 0), b1 = fn_eval(f.borders[size_t(lk) + 1], s, 0);
          const double td = double(b0 + Q(fr) * (b1 - b0));
          const Q t = td;
          const bool border = fr == 0.0 || fr == 1.0;
          /* the link as the evaluator picks it (Above): largest k with t >= b_k */
          int k = 0;
          for (int j = 1; j < m; j++) {
            if (t >= fn_eval(f.borders[size_t(j)], s, 0)) {
              k = j;
            }
          }
          const FnData &Bk = f.borders[size_t(k)], &Bk1 = f.borders[size_t(k) + 1];
          const FnData &Zk = f.heights[size_t(k)], &Zk1 = f.heights[size_t(k) + 1];
          Q bk[3], bk1[3], zk[3], zk1[3];
          for (int q = 0; q < 3; q++) {
            bk[q] = fn_eval(Bk, s, q);
            bk1[q] = fn_eval(Bk1, s, q);
            zk[q] = fn_eval(Zk, s, q);
            zk1[q] = fn_eval(Zk1, s, q);
          }
          const Q dd = bk1[0] - bk[0], dd1 = bk1[1] - bk[1], dd2 = bk1[2] - bk[2];
          const Q D = zk1[0] - zk[0], D1 = zk1[1] - zk[1], D2 = zk1[2] - zk[2];
          const Q w = (t - bk[0]) / dd;
          const Q ws = -(bk[1] + w * dd1) / dd, wt = 1 / dd;
          const Q wss = -(bk[2] + 2 * ws * dd1 + w * dd2) / dd, wst = -dd1 / (dd * dd);
          const Q Z = zk[0] + w * D, Zs = zk[1] + ws * D + w * D1, Zt = D / dd;
          const Q Zss = zk[2] + wss * D + 2 * ws * D1 + w * D2, Zst = wst * D + wt * D1;
          /* N' = -kappa T, N'' = -kappa' T - kappa^2 N, r'' = kappa N */
          const Q n1x = -kap * tx, n1y = -kap * ty;
          const Q n2x = -kap1 * tx - kap * kap * nx, n2y = -kap1 * ty - kap * kap * ny;
          const Q r2x = kap * nx, r2y = kap * ny;
          const Q v[15] = {x + t * nx, y + t * ny, Z,
                           tx + t * n1x, ty + t * n1y, Zs,
                           nx, ny, Zt,
                           r2x + t * n2x, r2y + t * n2y, Zss,
                           n1x, n1y, Zst};
          printf("  {%a, %a, %d, {", sd, td, border ? -1 : k);
          for (int i = 0; i < 15; i++) {
            printf("%a%s", double(v[i]), i < 14 ? ", " : "");
          }
          printf("}},\n");
        }
      }
    }
    printf("};\n");
    idx++;
  }
  printf("\nstatic const ubertopo::test::RoadOracleSet kRoadOracle[] = {\n");
  idx = 0;
  for (const RoadFixture &f : fx) {
    const int n = int(f.stations.size() * (f.borders.size() - 1) * f.fractions.size());
    printf("  {\"%s\", kRoad%d, %d},\n", f.name, idx, n);
    idx++;
  }
  printf("};\n");
  return 0;
}
